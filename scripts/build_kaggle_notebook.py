"""Build a self-contained Kaggle notebook that writes the repo's code, downloads RAGTruth and runs one job.

Kaggle can't see this repo, so each source file is embedded as a %%writefile cell. Rebuild after editing code:
  python3 scripts/build_kaggle_notebook.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CODE = ["data/prepare.py", "src/hd/__init__.py", "src/hd/data.py", "src/hd/metrics.py", "src/hd/baselines.py",
        "src/hd/model.py", "src/hd/train.py", "src/hd/judge.py", "src/hd/aggrefact.py", "eval/evaluate.py"]
RAGTRUTH = "https://raw.githubusercontent.com/ParticleMedia/RAGTruth/main/dataset"
HUB_MODEL = "shaunak-12/hallucination-detector-modernbert"


def md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip().splitlines(keepends=True)}


def code(text: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": text.strip().splitlines(keepends=True)}


def notebook(title: str, steps: list[str], note: str = "", ragtruth: bool = True) -> dict:
    cells = [
        md(f"""
# {title}

Generated by `scripts/build_kaggle_notebook.py`, so edit the repo instead of this notebook.

**Before running:** in the right panel, set *Accelerator* to **GPU T4** and turn **Internet** on
(Internet needs a phone-verified Kaggle account). Then use *Run All*. When it finishes, download
`results.zip` from the *Output* section and unzip it into the repo's `results/` folder.
{note}"""),
        code("!mkdir -p data src/hd eval results"),
    ]
    for path in CODE:
        text = (ROOT / path).read_text()
        # %%writefile rejects an empty cell body (e.g. an empty __init__.py)
        cells.append(code(f"%%writefile {path}\n" + text if text.strip() else f"!touch {path}"))
    if ragtruth:
        cells.append(code(
            "!mkdir -p data/raw\n"
            + "".join(f"!curl -sfL -o data/raw/{f}.jsonl {RAGTRUTH}/{f}.jsonl\n" for f in ("response", "source_info"))
            + "!python data/prepare.py > /dev/null && cat data/processed/stats.json | head -20"
        ))
    cells += [code(s) for s in steps]
    cells.append(code("!cd /kaggle/working && zip -qr results.zip results && ls -la results"))
    return {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                                        "name": "python3"}},
            "nbformat": 4, "nbformat_minor": 5}


UPLOAD = r"""
# Finds the checkpoint in the attached training-run output and pushes it to a private Hugging Face Hub repo.
import glob
import os

from huggingface_hub import HfApi
from kaggle_secrets import UserSecretsClient

REPO_NAME = "hallucination-detector-modernbert"

api = HfApi(token=UserSecretsClient().get_secret("HF_TOKEN"))
repo_id = f"{api.whoami()['name']}/{REPO_NAME}"
ckpts = sorted({os.path.dirname(p) for p in glob.glob("/kaggle/input/**/checkpoints/ft/config.json", recursive=True)})
assert len(ckpts) == 1, f"expected one checkpoints/ft in the attached input, found {ckpts or 'none'}"
ckpt = ckpts[0]
print("checkpoint:", ckpt, sorted(os.listdir(ckpt)))
assert any(f.endswith(".safetensors") for f in os.listdir(ckpt)), "no weights file in the checkpoint"

api.create_repo(repo_id, private=True, exist_ok=True)
api.upload_folder(repo_id=repo_id, folder_path=ckpt, commit_message="Run 1: 2 epochs, test F1 0.652, AUROC 0.916")
results = os.path.join(os.path.dirname(os.path.dirname(ckpt)), "results")
for name in ("ft_metrics.json", "ft_train_log.json"):
    if os.path.exists(os.path.join(results, name)):
        api.upload_file(repo_id=repo_id, path_or_fileobj=os.path.join(results, name), path_in_repo=f"results/{name}")
print("uploaded:", sorted(api.list_repo_files(repo_id)))
print(f"https://huggingface.co/{repo_id}")
"""


def upload_notebook() -> dict:
    return {"cells": [md("""
# Push the trained checkpoint to the Hugging Face Hub

Generated by `scripts/build_kaggle_notebook.py`. No GPU needed (*Accelerator: None*); *Internet* must be on.

**Before running:** (1) *Add-ons -> Secrets*: tick `HF_TOKEN` so this notebook can read it. (2) *Add Input*: add the
output of the training notebook (the version whose run produced the model). Then *Run All*.
"""), code(UPLOAD)],
            "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}},
            "nbformat": 4, "nbformat_minor": 5}


def main() -> None:
    notebooks = {
        "upload_hub_kaggle.ipynb": upload_notebook(),
        "aggrefact_kaggle.ipynb": notebook("LLM-AggreFact out-of-domain test", [
            "# HF_TOKEN reads the private model and the gated dataset; ! commands inherit os.environ\n"
            "import os\nfrom kaggle_secrets import UserSecretsClient\n"
            "os.environ['HF_TOKEN'] = UserSecretsClient().get_secret('HF_TOKEN')",
            "!nvidia-smi -L",
            "# smoke run: 200 test claims, about a minute\n"
            f"!PYTHONPATH=src python -m hd.aggrefact --model {HUB_MODEL} --splits test --limit 200 --out /tmp/smoke",
            f"!PYTHONPATH=src python -m hd.aggrefact --model {HUB_MODEL}",
        ], ragtruth=False, note="""
Also needed: *Add-ons -> Secrets*, tick `HF_TOKEN`; and accept the dataset's terms once at
https://huggingface.co/datasets/lytang/LLM-AggreFact while logged in to the same Hugging Face account.
Metrics are computed locally afterwards with `python eval/evaluate.py --aggrefact`.
"""),
        "nli_baseline_kaggle.ipynb": notebook("Zero-shot NLI baseline", [
            "!nvidia-smi -L",
            "# smoke run first: 200 sentences, should take well under a minute\n"
            "!PYTHONPATH=src python -m hd.baselines --splits val --limit 200 --out /tmp/smoke",
            "!PYTHONPATH=src python -m hd.baselines --splits val test",
            "!python eval/evaluate.py --method nli",
        ]),
        "train_kaggle.ipynb": notebook("Fine-tune ModernBERT", [
            "!nvidia-smi -L && python -c 'import torch, transformers; print(torch.__version__, transformers.__version__)'",
            "# smoke run: 64 balanced examples, train = val, must overfit (a few minutes)\n"
            "!PYTHONPATH=src python -m hd.train --smoke 64 --epochs 15 --lr 1e-4 --accum 1 --log-every 10 "
            "--out /tmp/smoke --ckpt /tmp/smoke/ckpt\n"
            "import json\n"
            "f1 = json.load(open('/tmp/smoke/ft_train_log.json'))['epochs'][-1]['val']['f1']\n"
            "assert f1 >= 0.9, f'smoke run did not overfit (val F1 {f1}); stop and inspect before the full run'",
            "!PYTHONPATH=src python -m hd.train",
            "!python eval/evaluate.py --method ft",
        ], note="""
This run takes hours, so start it with *Save Version* -> *Save & Run All (Commit)*. It then runs in the background
(12-hour limit) and the browser can be closed. The best checkpoint is also in the output under `checkpoints/ft/`.
"""),
    }
    for name, nb in notebooks.items():
        out = ROOT / "notebooks" / name
        out.write_text(json.dumps(nb, indent=1) + "\n")
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
